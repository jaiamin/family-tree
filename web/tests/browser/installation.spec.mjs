import { test, expect } from "@playwright/test";
import { sizedGedcom, syntheticGedcom } from "../fixtures/gedcom.mjs";
const basePath = process.env.BASE_PATH ?? "/family-tree";

test("owners manage trees and relatives browse privately without accounts", async ({page,browser}) => {
  const errors=[];page.on("pageerror",error=>errors.push(error.message));
  await page.route("**/*",route => new URL(route.request().url()).hostname === "localhost" ? route.continue() : route.abort());
  await page.goto(`${basePath}/`);
  await page.getByLabel("Password",{exact:true}).fill("local-preview-only");
  await page.getByRole("button",{name:"Continue",exact:true}).click();
  await expect(page.locator('summary[aria-label="Family menu"]')).toBeVisible();
  await page.context().addCookies([{name:"family_session",value:"synthetic-browser-owner",url:"http://localhost:8002",httpOnly:true}]);
  await page.reload();
  await page.getByRole("button",{name:"Create tree",exact:true}).click();
  await page.getByLabel("New tree name").fill("Our family");
  await page.getByRole("dialog").getByRole("button",{name:"Create tree",exact:true}).click();
  await page.getByRole("link",{name:"Our family 0 people"}).click();
  await page.getByRole("button",{name:"Add the first person"}).click();
  await page.getByRole("textbox",{name:"Name",exact:true}).fill("Parent Relative");
  await page.getByRole("button",{name:"Add person",exact:true}).click();
  await page.getByRole("button",{name:"Parent Relative",exact:true}).click();
  await page.getByRole("button",{name:"Add relative",exact:true}).click();
  await page.getByLabel("Relationship to Parent Relative").selectOption({label:"Child"});
  await page.getByRole("button",{name:"Add a new person"}).click();
  await page.getByRole("textbox",{name:"Name",exact:true}).fill("Child Relative");
  await page.getByLabel("Gender",{exact:true}).selectOption({label:"Female"});
  await page.getByRole("dialog",{name:"Add a relative",exact:true}).getByRole("button",{name:"Add relative",exact:true}).click();
  await expect(page.getByRole("button",{name:"Child Relative, Female",exact:true})).toBeVisible();
  const treeURL=page.url().split("#")[0];
  await page.getByRole("button",{name:"Close",exact:true}).click();
  await page.getByRole("button",{name:"List view",exact:true}).click();
  await expect(page.getByRole("button",{name:/Child Relative/}).first()).toBeVisible();
  await page.locator('summary[aria-label="Family menu"]').click();
  await page.getByRole("button",{name:"Editor access",exact:true}).click();
  await page.getByLabel("Google email").fill("relative@example.com");
  await page.getByRole("button",{name:"Add editor",exact:true}).click();
  await expect(page.getByText("Editor access saved.",{exact:true})).toBeVisible();
  await page.getByRole("dialog").getByRole("button",{name:"Close",exact:true}).click();
  const viewer=await browser.newContext(), relative=await viewer.newPage();
  await relative.goto(treeURL);
  await relative.getByLabel("Password",{exact:true}).fill("local-preview-only");
  await relative.getByRole("button",{name:"Continue",exact:true}).click();
  await expect(relative.getByRole("button",{name:/Child Relative/}).first()).toBeVisible();
  await relative.goto(treeURL);
  await relative.getByRole("button",{name:/Child Relative/}).first().click();
  await expect(relative.getByRole("button",{name:"Edit details"})).toHaveCount(0);
  await expect(relative.getByRole("button",{name:"Add photo"})).toBeVisible();
  await relative.getByRole("button",{name:"Suggest a change"}).click();
  await expect(relative.getByRole("dialog",{name:"Suggest a change",exact:true})).toBeVisible();
  await relative.setViewportSize({width:320,height:740});
  await expect(relative.getByRole("dialog",{name:"Suggest a change",exact:true})).toBeInViewport();
  expect(await relative.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await viewer.close();
  await page.locator('summary[aria-label="Family menu"]').click();
  await page.getByRole("button",{name:"Import GEDCOM",exact:true}).click();
  await page.getByLabel("Tree name",{exact:true}).fill("Imported family");
  await page.getByLabel("GEDCOM file",{exact:true}).setInputFiles({name:"family.ged",mimeType:"text/plain",buffer:Buffer.from("0 HEAD\n1 CHAR UTF-8\n0 @I1@ INDI\n1 NAME Imported Relative\n0 TRLR\n")});
  await page.getByRole("button",{name:"Preview import",exact:true}).click();
  await expect(page.getByText("1 person · A new tree will be created.",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Import tree",exact:true}).click();
  await expect(page.getByRole("dialog",{name:"Import GEDCOM",exact:true})).toHaveCount(0);
  const overview=await(await page.request.get(`${basePath}/api/view`)).json();
  expect(overview.trees.some(tree=>tree.name === "Imported family" && tree.people === 1)).toBe(true);
  expect(errors).toEqual([]);
});

for (const viewport of [{width:1280,height:800}, {width:320,height:740}]) {
  test(`GEDCOM imports larger than 1 MB and recoverable errors at ${viewport.width}px`, async ({page}) => {
    await page.setViewportSize(viewport);
    const errors=[]; page.on("pageerror", error => errors.push(error.message));
    await page.context().addCookies([{name:"family_session",value:"synthetic-browser-owner",url:"http://localhost:8002",httpOnly:true}]);
    await page.goto(`${basePath}/`);
    await page.locator('summary[aria-label="Family menu"]').click();
    await page.getByRole("button",{name:"Import GEDCOM",exact:true}).click();
    const panel=page.getByRole("dialog",{name:"Import GEDCOM",exact:true});
    await expect(panel.getByText(/Up to 5 MB and 100,000 lines/)).toBeVisible();
    await page.getByLabel("Tree name",{exact:true}).fill(`Large import ${viewport.width}`);
    const file=page.getByLabel("GEDCOM file",{exact:true});
    await file.setInputFiles({name:"oversized.ged",mimeType:"text/plain",buffer:Buffer.from(sizedGedcom(5_000_001))});
    await panel.getByRole("button",{name:"Preview import",exact:true}).click();
    await expect(panel.getByText("Choose a GEDCOM file of 5 MB or less.",{exact:true})).toBeVisible();
    await file.setInputFiles({name:"many-lines.ged",mimeType:"text/plain",buffer:Buffer.from("\n".repeat(100_000)+syntheticGedcom())});
    await panel.getByRole("button",{name:"Preview import",exact:true}).click();
    await expect(panel.getByText("Import a GEDCOM file with at most 100,000 lines.",{exact:true})).toBeVisible();
    await file.setInputFiles({name:"large.ged",mimeType:"text/plain",buffer:Buffer.from(sizedGedcom(1_200_000,"é"))});
    await panel.getByRole("button",{name:"Preview import",exact:true}).click();
    await expect(panel.getByText("1 person · A new tree will be created.",{exact:true})).toBeVisible();
    await expect(panel.getByText("Not imported: _PADDING.",{exact:true})).toBeVisible();
    await panel.getByRole("button",{name:"Import tree",exact:true}).click();
    await expect(panel).toHaveCount(0);
    await page.getByRole("link",{name:`Large import ${viewport.width} 1 person`,exact:true}).click();
    await page.getByRole("button",{name:"Imported 1",exact:true}).click();
    await expect(page.getByRole("dialog")).toBeInViewport();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect(errors).toEqual([]);
  });
}
